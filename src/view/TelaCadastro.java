    private void configurarDica(javax.swing.JTextField campo, String dica) {
        campo.setForeground(java.awt.Color.GRAY);
        campo.addFocusListener(new java.awt.event.FocusAdapter() {
            @Override
            public void focusGained(java.awt.event.FocusEvent e) {
                if (campo.getText().equals(dica)) {
                    campo.setText("");
                    campo.setForeground(java.awt.Color.BLACK);
                }
            }

            @Override
            public void focusLost(java.awt.event.FocusEvent e) {
                if (campo.getText().trim().isEmpty()) {
                    campo.setText(dica);
                    campo.setForeground(java.awt.Color.GRAY);
                }
            }
        });
    }

    private void configurarDicaSenha(javax.swing.JPasswordField campo) {
        final String dica = "Digite sua senha";
        campo.setEchoChar((char) 0);
        campo.setForeground(java.awt.Color.GRAY);
        campo.setText(dica);
        campo.addFocusListener(new java.awt.event.FocusAdapter() {
            @Override
            public void focusGained(java.awt.event.FocusEvent e) {
                if (new String(campo.getPassword()).equals(dica)) {
                    campo.setText("");
                    campo.setEchoChar('•');
                    campo.setForeground(java.awt.Color.BLACK);
                }
            }

            @Override
            public void focusLost(java.awt.event.FocusEvent e) {
                if (campo.getPassword().length == 0) {
                    campo.setEchoChar((char) 0);
                    campo.setText(dica);
                    campo.setForeground(java.awt.Color.GRAY);
                }
            }
        });
    }

