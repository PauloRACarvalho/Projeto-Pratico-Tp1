    public TelaLogin(GerenciarUsuarios gerenciarUsuarios) {
        this.gerenciarUsuarios = gerenciarUsuarios;
        initComponents();
       
        final String dicaEmail = "Digite seu email";

        txtEmail.setText(dicaEmail);
        txtEmail.setForeground(java.awt.Color.GRAY);

        txtEmail.addFocusListener(new java.awt.event.FocusAdapter() {
            @Override
            public void focusGained(java.awt.event.FocusEvent evt) {
                if (txtEmail.getText().equals(dicaEmail)) {
                    txtEmail.setText("");
                    txtEmail.setForeground(java.awt.Color.BLACK);
                }
            }

            @Override
            public void focusLost(java.awt.event.FocusEvent evt) {
                if (txtEmail.getText().trim().isEmpty()) {
                    txtEmail.setText(dicaEmail);
                    txtEmail.setForeground(java.awt.Color.GRAY);
                }
            }
        });

        
        final String dicaSenha = "Digite sua senha";
        final char mascara = txtSenha.getEchoChar();

        txtSenha.setEchoChar((char) 0);
        txtSenha.setText(dicaSenha);
        txtSenha.setForeground(java.awt.Color.GRAY);

        txtSenha.addFocusListener(new java.awt.event.FocusAdapter() {
            @Override
            public void focusGained(java.awt.event.FocusEvent evt) {
                if (new String(txtSenha.getPassword()).equals(dicaSenha)) {
                    txtSenha.setText("");
                    txtSenha.setEchoChar(mascara);
                    txtSenha.setForeground(java.awt.Color.BLACK);
                }
            }

            @Override
            public void focusLost(java.awt.event.FocusEvent evt) {
                if (txtSenha.getPassword().length == 0) {
                    txtSenha.setEchoChar((char) 0);
                    txtSenha.setText(dicaSenha);
                    txtSenha.setForeground(java.awt.Color.GRAY);
                }
            }
        });

        
        btnLogin.requestFocusInWindow();

        
        getRootPane().setDefaultButton(btnLogin);
    }
    


